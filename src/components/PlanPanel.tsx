"use client";

import { useState } from "react";
import { CITATIONS } from "@/lib/grounding/citations";
import type { PreparedPlan } from "@/lib/plan/types";
import type { HouseholdProfile } from "@/lib/profile/types";
import { citationLabel, describeAge, describeGap, uniqueCitations } from "@/lib/view/describe";
import { Evidence, Quotes } from "./Evidence";
import { useLocale } from "./LocaleContext";

type Load = { status: "idle" } | { status: "loading" } | { status: "failed" } | { status: "ready"; data: PreparedPlan; receivedAt: Date };

/**
 * The Gemini-written plan, only on request: nothing is generated by opening the
 * page. Shown only after the server has validated all of it; on any failure,
 * one honest message and a retry. Never a partial plan.
 *
 * Remount (by key) when the language or answers change, which returns it to idle.
 */
export function PlanPanel({
  profile,
  live,
  walkingGated,
  poorDay,
}: {
  profile: HouseholdProfile;
  live: { reading: boolean; forecast: boolean };
  walkingGated: boolean;
  poorDay: boolean;
}) {
  const { t, f, locale } = useLocale();
  const [load, setLoad] = useState<Load>({ status: "idle" });

  const fetchPlan = async () => {
    setLoad({ status: "loading" });
    try {
      const res = await fetch("/api/plan", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ cityId: profile.cityId, locale, profile }),
      });
      if (!res.ok) throw new Error(String(res.status));
      setLoad({ status: "ready", data: (await res.json()) as PreparedPlan, receivedAt: new Date() });
    } catch {
      setLoad({ status: "failed" });
    }
  };

  const button = (label: string) => (
    <button type="button" onClick={() => void fetchPlan()} className="mt-3 rounded-full bg-ink px-5 py-2 font-medium text-smog">
      {label}
    </button>
  );

  return (
    <section aria-labelledby="plan-title" className="border-t-2 border-ink/15 pt-5">
      <h2 id="plan-title" className="type-condensed text-3xl font-semibold">
        {t.plan.title}
      </h2>
      <p className="mt-1 text-sm text-muted">{t.plan.byline}</p>

      <div aria-live="polite">
        {load.status === "idle" && button(t.plan.get)}
        {load.status === "loading" && <p className="mt-4 text-muted">{t.plan.loading}</p>}
        {load.status === "failed" && (
          <div className="mt-4">
            <p>{t.plan.unavailable(live)}</p>
            {button(t.plan.retry)}
          </div>
        )}
        {/* A reused plan may predate today's poor air: don't show one written without the poor-day wording, or that suggests walking. */}
        {load.status === "ready" && ((poorDay && !load.data.poorDay) || (walkingGated && load.data.plan.steps.some((s) => s.refId.endsWith("->walk-cycle")))) ? (
          <p className="mt-4">{t.plan.outdated}</p>
        ) : load.status === "ready" && (
          <div className="mt-4">
            {/* A plan is reused for up to three hours, so its age is stated like a reading's. */}
            <p className="text-sm font-medium">
              {t.plan.preparedAt({
                time: f.time(load.data.preparedAt),
                ago: describeAge(load.data.preparedAt, load.receivedAt, t),
                reading: load.data.readingUtc === null ? null : f.time(load.data.readingUtc),
              })}
            </p>
            {load.data.outlook.length > 0 && <p className="mt-1 text-sm text-model">{t.plan.outlookUsed({ items: load.data.outlook })}</p>}
            <p className="mt-2 text-xl font-semibold">{load.data.plan.headline}</p>
            <ol className="mt-4 space-y-4">
              {load.data.plan.steps.map((step) => {
                const ref = load.data.refs[step.refId];
                return (
                  <li key={step.refId} className="border-l-2 border-ink/25 pl-4">
                    <p>{step.note}</p>
                    {ref?.kind === "window" && <p className="mt-1 text-sm text-model">{t.plan.seeForecast}</p>}
                    {ref?.kind === "guidance" && (
                      <div className="mt-1 text-sm text-muted">
                        {uniqueCitations(ref.sources.map((s) => s.citation)).map((id) => (
                          <p key={id} className="mt-0.5 text-xs">
                            <a className="underline underline-offset-2" href={CITATIONS[id].url}>
                              {t.plan.source({ title: citationLabel(id) })}
                            </a>
                          </p>
                        ))}
                        {/* The cited words, one tap away, so a reader can compare them with the note. */}
                        <Evidence summary={t.plan.sourceSays}>
                          {t.indoor.translationNote && (
                            <div>
                              <p className="text-ink">{ref.text}</p>
                              <p className="text-xs">{t.indoor.translationNote}</p>
                            </div>
                          )}
                          <p className="font-medium text-ink">{t.indoor.originalWording}</p>
                          <Quotes items={ref.sources} />
                        </Evidence>
                      </div>
                    )}
                    {ref?.kind === "swap" && (
                      <div className="mt-1 text-sm text-muted">
                        <p className="font-medium text-ink">{ref.action}</p>
                        <p>{ref.saving}</p>
                        {ref.onlyIfAvailable && <p className="italic">{t.swaps.ifAvailable}</p>}
                        {uniqueCitations(ref.factors.map((x) => x.citation)).map((id) => (
                          <p key={id} className="mt-0.5 text-xs">
                            <a className="underline underline-offset-2" href={CITATIONS[id].url}>
                              {t.plan.source({ title: citationLabel(id) })}
                            </a>
                          </p>
                        ))}
                        {/* These quotes are from other documents than the figure's link above, so each names its own. */}
                        <Evidence summary={t.plan.sourceSays}>
                          {ref.co2Only && <p className="text-ink">{t.swapsSection.co2OnlyNotes[ref.co2Only]}</p>}
                          <p className="font-medium text-ink">{t.indoor.originalWording}</p>
                          <Quotes items={ref.why} />
                        </Evidence>
                      </div>
                    )}
                  </li>
                );
              })}
            </ol>
            {load.data.plan.acknowledgedGaps.length > 0 && (
              <div className="mt-4 text-sm">
                <p className="font-medium">{t.plan.gapsIntro}</p>
                <ul className="mt-1 list-disc pl-5 text-muted">
                  {load.data.plan.acknowledgedGaps.map((g) => (
                    <li key={g}>{describeGap(g, t)}</li>
                  ))}
                </ul>
              </div>
            )}
          </div>
        )}
      </div>
    </section>
  );
}
